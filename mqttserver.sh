#!/bin/sh
# MIT License
# Mosquitto MQTT Broker Install Script
# Support: Ubuntu / Debian / Alpine Linux
# Author: Self
# Usage: chmod +x install_mosquitto.sh && ./install_mosquitto.sh

set -e

# 检测系统
if [ -f /etc/os-release ]; then
    . /etc/os-release
fi

IS_ALPINE=0
IS_DEB=0
if echo "$ID" | grep -qi alpine; then
    IS_ALPINE=1
elif echo "$ID" | grep -qi "debian\|ubuntu"; then
    IS_DEB=1
else
    echo "[ERROR] Unsupported OS, only Ubuntu/Debian/Alpine"
    exit 1
fi

# 交互式输入配置
echo "==== Mosquitto MQTT 安装配置 ===="
printf "请输入MQTT监听端口: "
read MQTT_PORT
printf "请输入MQTT用户名: "
read MQTT_USER
printf "请输入MQTT密码: "
read -s MQTT_PASS
echo ""
printf "是否开启WebSocket(默认9001+port偏移，y/n): "
read ENABLE_WS

# 简单校验
if [ -z "$MQTT_PORT" ] || [ -z "$MQTT_USER" ] || [ -z "$MQTT_PASS" ];then
    echo "[ERROR] 端口、用户名、密码不能为空"
    exit 1
fi

# 配置文件路径
MOSQ_CONF="/etc/mosquitto/mosquitto.conf"
MOSQ_PW="/etc/mosquitto/pwfile"

echo "[INFO] Start install mosquitto..."

if [ $IS_DEB -eq 1 ]; then
    apt update -y
    apt install -y mosquitto mosquitto-clients
elif [ $IS_ALPINE -eq 1 ]; then
    apk update
    apk add mosquitto mosquitto-clients
fi

# 备份原有配置
if [ -f "$MOSQ_CONF" ]; then
    cp "$MOSQ_CONF" "${MOSQ_CONF}.bak.$(date +%Y%m%d_%H%M%S)"
fi

# 清空配置，写入新配置
cat > "$MOSQ_CONF" <<EOF
# Auto generated by install_mosquitto.sh
listener ${MQTT_PORT} 0.0.0.0
allow_anonymous false
password_file ${MOSQ_PW}

persistence true
persistence_location /var/lib/mosquitto/
log_dest file /var/log/mosquitto/mosquitto.log
log_type notice information error
max_connections 1000
EOF

# 追加websocket
if [ "$ENABLE_WS" = "y" ] || [ "$ENABLE_WS" = "Y" ];then
    WS_PORT=$((MQTT_PORT + 100))
    cat >> "$MOSQ_CONF" <<EOF
listener ${WS_PORT} 0.0.0.0
protocol websockets
allow_anonymous false
password_file ${MOSQ_PW}
EOF
fi

# 生成密码文件
mosquitto_passwd -c -b "$MOSQ_PW" "$MQTT_USER" "$MQTT_PASS"
chown mosquitto:mosquitto "$MOSQ_PW"
chmod 600 "$MOSQ_PW"

# 防火墙放行
if [ $IS_DEB -eq 1 ]; then
    if command -v ufw >/dev/null 2>&1; then
        ufw allow ${MQTT_PORT}/tcp
        if [ "$ENABLE_WS" = "y" ] || [ "$ENABLE_WS" = "Y" ];then
            ufw allow ${WS_PORT}/tcp
        fi
        ufw reload
    fi
elif [ $IS_ALPINE -eq 1 ]; then
    iptables -A INPUT -p tcp --dport ${MQTT_PORT} -j ACCEPT
    if [ "$ENABLE_WS" = "y" ] || [ "$ENABLE_WS" = "Y" ];then
        iptables -A INPUT -p tcp --dport ${WS_PORT} -j ACCEPT
    fi
fi

# 启停+开机自启
if [ $IS_DEB -eq 1 ]; then
    systemctl enable --now mosquitto
    systemctl restart mosquitto
elif [ $IS_ALPINE -eq 1 ]; then
    rc-update add mosquitto default
    rc-service mosquitto start
    rc-service mosquitto restart
fi

echo ""
echo "==================== 安装完成 ===================="
echo "MQTT TCP Port: ${MQTT_PORT}"
if [ "$ENABLE_WS" = "y" ] || [ "$ENABLE_WS" = "Y" ];then
    echo "MQTT Websocket Port: ${WS_PORT}"
fi
echo "User: ${MQTT_USER}"
echo "Password: 你设置的密码"
echo ""
echo "测试订阅命令："
echo "mosquitto_sub -h 127.0.0.1 -p ${MQTT_PORT} -u ${MQTT_USER} -P \"你的密码\" -t test/hello"
echo "测试发布命令："
echo "mosquitto_pub -h 127.0.0.1 -p ${MQTT_PORT} -u ${MQTT_USER} -P \"你的密码\" -t test/hello -m \"hello from script\""
echo ""
echo "日志查看："
if [ $IS_DEB -eq 1 ]; then
    echo "journalctl -u mosquitto -f"
else
    echo "tail -f /var/log/mosquitto/mosquitto.log"
fi
echo "=================================================="